a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("Sum:", a + b)
print("Difference:", a - b)
print("Product:", a * b)
print("Division:", a / b)

print("a is Even" if a % 2 == 0 else "a is Odd")
print("b is Even" if b % 2 == 0 else "b is Odd")

print("Float of a:", float(a))